"""Original, periodic machinery beds for After Play. No external samples."""
from pathlib import Path
import hashlib, json, subprocess
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'games/kinderparadies/assets/atmosphere-v320'
OUT.mkdir(parents=True, exist_ok=True)
RATE, SECONDS = 24000, 8
t = np.arange(RATE * SECONDS) / RATE
rng = np.random.default_rng(320)

def noise(cutoff):
    spectrum = np.fft.rfft(rng.standard_normal(t.size))
    frequency = np.fft.rfftfreq(t.size, 1 / RATE)
    spectrum *= np.exp(-(frequency / cutoff) ** 2)
    spectrum[0] = 0
    data = np.fft.irfft(spectrum, n=t.size)
    return data / max(data.std(), .001)

def tone(hz):
    return np.sin(2 * np.pi * hz * t)

tracks = {}
for i, hz in enumerate([50, 62.5, 75]):
    motor = (.72 * tone(hz) + .19 * tone(hz * 2) + .065 * tone(hz * 3))
    motor *= 1 + .045 * tone(.25 + i * .125)
    tracks[f'arcade-{i + 1}'] = motor + noise(850) * .035 + tone(1250 + 125 * i) * .006
tracks['fridge-compressor'] = (tone(50) * .60 + tone(100) * .22 + tone(150) * .06) * (1 + .06 * tone(.375)) + noise(380) * .06
shutter = (.5 + .5 * tone(24)) ** 6
tracks['projector-mechanism'] = noise(2300) * shutter * .19 + tone(96) * .12 + noise(310) * .12
tracks['vent-air'] = noise(620) * .44 + tone(50) * .08
tracks['electrical-cabinet'] = tone(100) * .40 + tone(200) * .09 + noise(180) * .04
tracks['tube-resonance'] = noise(270) * .13 + tone(87.5) * .05 + tone(175) * .025
report = {}
for name, sound in tracks.items():
    sound *= 10 ** (-21 / 20) / max(np.sqrt(np.mean(sound ** 2)), .001)
    sound = np.clip(sound, -.75, .75).astype('<f4')
    target = OUT / (name + '.ogg')
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'f32le', '-ar', str(RATE), '-ac', '1', '-i', 'pipe:0', '-c:a', 'libvorbis', '-q:a', '3', str(target)], input=sound.tobytes(), check=True)
    report[name] = {'duration': SECONDS, 'rms_dbfs': -21, 'peak_dbfs': round(float(20 * np.log10(np.max(np.abs(sound)))), 2), 'bytes': target.stat().st_size, 'sha256': hashlib.sha256(target.read_bytes()).hexdigest()}
(OUT / 'audio-provenance.json').write_text(json.dumps({'origin': 'Original procedural machinery recordings generated by tools/prepare-after-play-v320-audio.py; periodic FFT noise and harmonic motors, no external audio.', 'tracks': report}, indent=2) + '\n', encoding='utf-8')
print('Created', len(tracks), 'distinct seamless machinery beds;', sum(x['bytes'] for x in report.values()), 'bytes.')
