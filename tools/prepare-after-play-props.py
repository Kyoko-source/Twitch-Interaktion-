"""Deterministic, gravity-settled disordered ball packing; no intersecting balls."""
from pathlib import Path
import numpy as np

root = Path(__file__).resolve().parents[1]

def pack(seed):
    rng = np.random.default_rng(seed)
    balls = []
    for _ in range(360):
        candidates = rng.uniform([-.4, 4.65], [5.5, 7.35], size=(96, 2))
        heights = np.full(96, .17)
        if balls:
            previous = np.asarray(balls)
            distances = ((candidates[:, None, :] - previous[None, :, [0, 2]]) ** 2).sum(axis=2)
            support = np.where(distances < .284**2,
                               previous[None, :, 1] + np.sqrt(np.maximum(0, .284**2-distances)), .17)
            heights = np.maximum(heights, support.max(axis=1))
        # A small jitter would still greedily pack the floor into a near-perfect
        # hex grid (every candidate scores almost identically there); weight it
        # enough that the bottom layer settles unevenly like a real dumped pile.
        chosen = np.argmin(heights + rng.uniform(0, .05, 96))
        balls.append([candidates[chosen, 0], heights[chosen], candidates[chosen, 1]])
    return np.asarray(balls)

def floating_safe(positions):
    # Every third ball (by placement order) periodically rises by 0.75-1.25m
    # in-game while the rest of the pile stays put; a stack that only cleared
    # .284m through height separation can end up inside a static neighbour.
    floating = np.arange(0, 360, 3)
    static = np.setdiff1d(np.arange(360), floating)
    still = positions[static]
    for offset in np.linspace(.7, 1.3, 13):
        lifted = positions[floating].copy();lifted[:, 1] += offset
        delta = lifted[:, None, :] - still[None, :, :]
        if (np.sqrt((delta ** 2).sum(axis=2)) < .284).any():
            return False
    return True

for seed in range(2113, 2113 + 200):
    positions = pack(seed)
    distances = np.linalg.norm(positions[:, None]-positions[None, :], axis=2)
    np.fill_diagonal(distances, np.inf)
    if distances.min() >= .28399 and floating_safe(positions):
        break
else:
    raise RuntimeError('No seed produced a floating-safe packing')
balls = positions.tolist()
print('used seed', seed)
out = root/'games/kinderparadies/scripts/ball_packing.gd'
out.write_text('class_name BallPacking\nextends RefCounted\n\n# Generated by tools/prepare-after-play-props.py; radius .14 m, clearance .004 m.\nconst POSITIONS: Array[Vector3]=[\n'+',\n'.join(' Vector3(%.6f,%.6f,%.6f)' % tuple(p) for p in balls)+'\n]\n', encoding='utf-8')
print('360 balls; minimum spacing', distances.min(), 'maximum centre height', positions[:, 1].max())
